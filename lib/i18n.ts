/**
 * Returns the translated name of a country record for the given language.
 * Falls back to the English name (`name_en`) when the requested language
 * is unavailable.
 */
export function countryName(country: { [key: string]: any }, lang: Lang): string {
  const translated = country[`name_${lang}`] as string | undefined;
  if (translated && translated.length > 0) return translated;
  return (country.name_en as string | undefined) ?? "";
}

/**
 * Whether a language is written right-to-left.
 * Arabic (`ar`), Persian (`fa`), and Urdu (`ur`) are the RTL languages.
 */
export function isRTL(lang: Lang): boolean {
  return lang === "ar" || lang === "fa" || lang === "ur";
}

