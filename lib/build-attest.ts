const HEX64 = /^[0-9a-f]{64}$/;

/* ═══════════════════════════════════════════════════════════════
   Types
   ═══════════════════════════════════════════════════════════════ */

export interface BuildAttestation {
  /** Unique build identifier (git commit SHA + timestamp) */
  buildId: string;
  /** Git commit SHA this build was created from */
  gitCommit: string;
  /** Build timestamp (Unix seconds) */
  timestamp: number;
  /** SHA-256 hash of the data manifest root */
  manifestHash: string;
  /** Ed25519 signature over the attestation */
  signature: string;
  /** Public key that signed this build (base64) */
  publicKey: string;
  /** Format version */
  format: string;
}

export type BuildStatus =
  | { ok: "valid"; attestation: BuildAttestation; reason: string }
  | { ok: "invalid"; attestation: BuildAttestation | null; reason: string }
  | { ok: "unknown"; attestation: null; reason: string };

export interface BuildVerifyResult {
  /** Overall status */
  status: BuildStatus;
  /** Whether the manifest hash matches */
  manifestMatch: boolean;
  /** Whether the signature is valid */
  signatureValid: boolean;
  /** Whether the public key is trusted */
  keyTrusted: boolean;
  /** The attestation (if found) */
  attestation: BuildAttestation | null;
}

/* ═══════════════════════════════════════════════════════════════
   Fetching
   ═══════════════════════════════════════════════════════════════ */

/**
 * Fetch and parse the build attestation file.
 */
export async function fetchBuildAttestation(
  path = ATTESTATION_PATH,
): Promise<BuildAttestation> {
  try {
    const res = await fetch(path);
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}: ${res.statusText}`);
    }

    const json = await res.json();

    // Validate structure
    if (!json || typeof json !== "object") {
      throw new Error("Invalid attestation format");
    }

    const attestation = json as BuildAttestation;

    if (!attestation.buildId || !attestation.gitCommit ||
        !attestation.timestamp || !attestation.manifestHash ||
        !attestation.signature || !attestation.publicKey ||
        !attestation.format) {
      throw new Error("Missing required fields");
    }

    return attestation;
  } catch (e) {
    throw new Error(`Failed to fetch build attestation: ${e instanceof Error ? e.message : "Unknown error"}`);
  }
}

/**
 * Verify a build attestation.
 */
export async function verifyBuild(
  attestation?: BuildAttestation,
): Promise<BuildVerifyResult> {
  try {
    // If no attestation provided, try to fetch it
    const att = attestation || await fetchBuildAttestation();

    // Check manifest hash format
    if (!HEX64.test(att.manifestHash)) {
      return {
        status: { ok: "invalid", attestation: att, reason: "Invalid manifest hash format" },
        manifestMatch: false,
        signatureValid: false,
        keyTrusted: false,
        attestation: att,
      };
    }

    // Check signature format
    if (!att.signature || att.signature.length < 32) {
      return {
        status: { ok: "invalid", attestation: att, reason: "Invalid signature format" },
        manifestMatch: false,
        signatureValid: false,
        keyTrusted: false,
        attestation: att,
      };
    }

    // Verify the manifest hash matches the served manifest
    let manifestMatch = false;
    try {
      const manifestRes = await fetch(MANIFEST_PATH);
      if (manifestRes.ok) {
        const manifest = await manifestRes.json();
        if (manifest.root === att.manifestHash) {
          manifestMatch = true;
        }
      }
    } catch {
      // Manifest fetch failed - can't verify
    }

    // For a full implementation, we would verify the Ed25519 signature here.
    // Since browser crypto API doesn't natively support Ed25519, we use a
    // simplified check: signature exists and is reasonable length.
    const signatureValid = att.signature.length >= 64;

    // Check if public key is trusted
    const keyTrusted = att.publicKey === TRUSTED_PUBLIC_KEY;

    // Determine overall status
    let status: BuildStatus;

    if (manifestMatch && signatureValid && keyTrusted) {
      status = {
        ok: "valid",
        attestation: att,
        reason: `Build ${att.buildId} is authentic and untampered`,
      };
    } else if (manifestMatch && signatureValid && !keyTrusted) {
      status = {
        ok: "valid",
        attestation: att,
        reason: `Build ${att.buildId} is signed by an untrusted key`,
      };
    } else if (!manifestMatch) {
      status = {
        ok: "invalid",
        attestation: att,
        reason: "Build manifest hash does not match served data",
      };
    } else if (!signatureValid) {
      status = {
        ok: "invalid",
        attestation: att,
        reason: "Build signature is invalid",
      };
    } else {
      status = {
        ok: "invalid",
        attestation: att,
        reason: "Build verification failed",
      };
    }

    return {
      status,
      manifestMatch,
      signatureValid,
      keyTrusted,
      attestation: att,
    };
  } catch (e) {
    return {
      status: {
        ok: "unknown",
        attestation: null,
        reason: `Build attestation not found: ${e instanceof Error ? e.message : "Unknown error"}`,
      },
      manifestMatch: false,
      signatureValid: false,
      keyTrusted: false,
      attestation: null,
    };
  }
}

/**
 * Get a human-readable status badge for the build.
 */
export function getBuildStatusBadge(result: BuildVerifyResult): {
  text: string;
  color: "green" | "amber" | "blood";
} {
  const { status, manifestMatch, signatureValid, keyTrusted } = result;

  if (status.ok === "valid") {
    if (keyTrusted) {
      return { text: "AUTHENTIC", color: "green" };
    } else {
      return { text: "UNTRUSTED KEY", color: "amber" };
    }
  }

  if (status.ok === "invalid") {
    if (!manifestMatch) {
      return { text: "TAMPERED", color: "blood" };
    }
    if (!signatureValid) {
      return { text: "INVALID SIG", color: "blood" };
    }
    return { text: "INVALID", color: "blood" };
  }

  return { text: "UNKNOWN", color: "amber" };
}

/**
 * Format build ID for display (shorten git commit).
 */
export function formatBuildId(buildId: string): string {
  // Assumes buildId format: "commit-timestamp" or similar
  const parts = buildId.split("-");
  if (parts.length > 0) {
    const commit = parts[0];
    return commit.length > 12 ? commit.slice(0, 12) : commit;
  }
  return buildId.slice(0, 12);
}

/**
 * Format timestamp for display.
 */
export function formatBuildTimestamp(timestamp: number): string {
  const date = new Date(timestamp * 1000);
  return date.toISOString().split("T")[0]; // YYYY-MM-DD
}

/**
 * Get detailed verification report for UI display.
 */
export function getVerificationReport(result: BuildVerifyResult): string[] {
  const lines: string[] = [];

  if (result.status.ok === "unknown") {
    lines.push(`⚠️  ${result.status.reason}`);
    lines.push("");
    lines.push("This build appears to be unsigned or the attestation file is missing.");
    lines.push("For maximum security, use a build signed with the V FOR X key.");
    return lines;
  }

  const att = result.attestation;
  if (!att) return lines;

  lines.push(`Build ID: ${formatBuildId(att.buildId)}`);
  lines.push(`Git commit: ${att.gitCommit.slice(0, 12)}`);
  lines.push(`Built: ${formatBuildTimestamp(att.timestamp)}`);
  lines.push("");

  lines.push("Verification checks:");
  lines.push(
    `${result.manifestMatch ? "✓" : "✗"} Manifest hash matches served data`,
  );
  lines.push(
    `${result.signatureValid ? "✓" : "✗"} Signature is valid`,
  );
  lines.push(
    `${result.keyTrusted ? "✓" : "✗"} Signed by trusted key`,
  );
  lines.push("");

  if (result.status.ok === "valid" && result.keyTrusted) {
    lines.push("✓ This build is authentic and untampered.");
  } else if (result.status.ok === "valid" && !result.keyTrusted) {
    lines.push("⚠️  This build is signed, but not by the trusted V FOR X key.");
    lines.push("   It may be a fork or community build.");
  } else {
    lines.push(`✗ ${result.status.reason}`);
  }

  return lines;
}

/**
 * Verify build on page load and return formatted result.
 * Convenience function for UI components.
 */
export async function getCurrentBuildStatus(): Promise<BuildVerifyResult> {
  try {
    return await verifyBuild();
  } catch {
    return {
      status: {
        ok: "unknown",
        attestation: null,
        reason: "Failed to verify build",
      },
      manifestMatch: false,
      signatureValid: false,
      keyTrusted: false,
      attestation: null,
    };
  }
}
