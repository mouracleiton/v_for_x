/**
 * V FOR X — Build Attestation (build authenticity verification)
 *
 * Client-side build verification using cosign/minisign signatures.
 * This module verifies that a static build (out/) is authentic and
 * untampered by checking cryptographic signatures against a known
 * trusted key.
 *
 * Protocol:
 *   1. SIGN — build pipeline signs the build output with a private key
 *      (scripts/write_build_attest.py writes BUILD_ATTESTATION.json)
 *   2. VERIFY — verifyBuild() checks the signature against the trusted
 *      public key and verifies the manifest hash matches the build.
 *   3. DISPLAY — UI shows green/amber/red status based on verification.
 *
 * The attestation file is served at /BUILD_ATTESTATION.json and contains:
 *   - buildId: unique build identifier (git commit + timestamp)
 *   - manifestHash: SHA-256 of the data manifest root
 *   - signature: Edwards-curve signature over the attestation
 *   - publicKey: The public key that signed this build
 *   - timestamp: Unix timestamp when build was signed
 *
 * Browser API: Web Crypto (crypto.subtle), fetch. No server required.
 */

